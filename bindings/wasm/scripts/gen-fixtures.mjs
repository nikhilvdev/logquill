// Packs the shared fixtures (schema/corpus/*.json, the golden files) into one ES module of strings, so a
// browser, Deno and a Worker read them without a filesystem. Generated, not committed (see .gitignore);
// `npm run build:hosts` calls this before any host runs.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const schema = fileURLToPath(new URL("../../../schema/", import.meta.url));
const out = fileURLToPath(new URL("../tests/hosts/fixtures.generated.mjs", import.meta.url));

const files = {};
for (const name of readdirSync(`${schema}corpus`).filter((f) => f.endsWith(".json")).sort()) {
  files[`corpus/${name}`] = readFileSync(`${schema}corpus/${name}`, "utf8");
}
for (const name of ["golden_records.json", "golden_chain.json"]) {
  files[name] = readFileSync(`${schema}${name}`, "utf8");
}

mkdirSync(new URL("../tests/hosts/", import.meta.url), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/gen-fixtures.mjs from schema/. Do not edit.\nexport const files = ${JSON.stringify(files)};\n`,
);
console.log(`packed ${Object.keys(files).length} fixture files into tests/hosts/fixtures.generated.mjs`);
